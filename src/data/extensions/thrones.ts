// New in this app: clearer throne info on the site pane. Sites with rarity 11-13 are thrones (the
// Sites page "Kind" filter already offers them). `wilddefenders` is just a flag: the defending army
// is engine logic, not game data, so only its presence is shown.
const WILD_DEFENDERS_NOTE = 'Guarded by a wild defender army. The army itself is generated by the game and is not in the data files.';

/** Rewrites the upstream "wild defenders: 1" row of a site pane to "yes", with an explanatory tooltip. */
export function withThroneInfo(o: any, html: string): string {
  if (!o || !o.wilddefenders || o.wilddefenders === '0') return html;
  return html.replace(
    /<tr class="wilddefenders ([^"]*)" ?>(\s*<th>[\s\S]*?<\/th>\s*)<td>[^<]*<\/td>/,
    `<tr class="wilddefenders $1" title="${WILD_DEFENDERS_NOTE}">$2<td>yes</td>`,
  );
}
