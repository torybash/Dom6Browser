import { describe, expect, it } from 'vitest';
import vanillaDm from '../src/data/poptypes/vanilla.dm?raw';
import meta from '../src/data/poptypes/poptypes.meta.json';
import { pdTroopCount, type IndependentsApi } from '../src/data/extensions/independents';
import { vanilla, withMods } from './helpers';

const api = async (): Promise<IndependentsApi> => (await vanilla()).Independents;
const ids = (list: { id: number }[]) => list.map((x) => x.id);

describe('generated vanilla.dm', () => {
  const lines = vanillaDm.split('\n');
  const header = lines.filter((l) => l.startsWith('--') && lines.indexOf(l) < 10);

  it('starts with a provenance header that matches the sidecar', () => {
    expect(header.join('\n')).toContain('GENERATED, do not edit');
    expect(header.join('\n')).toMatch(/Generated by scripts\/extract-poptypes\.py from Dominions6\.exe$/m);
    const m = header.join('\n').match(/exe size: (\d+) bytes, sha256: ([0-9a-f]{64})/);
    expect(m).not.toBeNull();
    expect(meta.provenance.exe.size).toBe(Number(m![1]));
    expect(meta.provenance.exe.sha256).toBe(m![2]);
  });

  it('is one #selectpoptype ... #end block per poptype, in id order, using only mod commands', () => {
    const cmds = lines.filter((l) => l.startsWith('#'));
    const allowed = /^#(selectpoptype|addrecunit|addreccom|defunit1[bc]?|defmult1[bc]?|defcom1|end) -?\d+( -- .*)?$|^#end$/;
    expect(cmds.filter((c) => !allowed.test(c))).toEqual([]);
    const selects = cmds.filter((c) => c.startsWith('#selectpoptype')).map((c) => parseInt(c.split(' ')[1]));
    expect(selects.length).toBe(82);
    expect(selects).toEqual([...selects].sort((a, b) => a - b));
    expect(cmds.filter((c) => c === '#end').length).toBe(82);
    expect(Object.keys(meta.poptypes).map(Number)).toEqual(selects);
  });

  it('writes each province defence key once per block (shadowed pairs live in the sidecar only)', () => {
    let block: string[] = [];
    for (const l of lines) {
      if (l.startsWith('#selectpoptype')) block = [];
      else if (/^#(defunit|defmult|defcom)/.test(l)) {
        const key = l.split(' ')[0];
        expect(block, l).not.toContain(key);
        block.push(key);
      }
    }
    expect(meta.poptypes['38'].shadowedPd).toEqual([['defunit1b', 271]]);
    expect(meta.poptypes['58'].shadowedPd).toEqual([['defunit1b', 49]]);
    expect(meta.poptypes['86'].shadowedPd).toEqual([['defunit1', 1393]]);
  });
});

describe('DMI.Independents (vanilla)', () => {
  it('has the 82 vanilla poptypes, none modded, no data errors', async () => {
    const DMI = await vanilla();
    const I = DMI.Independents as IndependentsApi;
    expect(DMI.errors).toEqual([]);
    expect(I.all.length).toBe(82);
    expect(ids(I.all)[0]).toBe(25);
    expect(ids(I.all).at(-1)).toBe(106);
    expect(I.all.every((p) => p.vanilla && !p.modded && p.modfiles.length === 0)).toBe(true);
    expect(I.all.every((p) => p.nameSource === 'manual v6.36')).toBe(true);
    // every referenced unit exists
    for (const p of I.all) {
      for (const u of [...p.recruits, ...p.commanders, ...p.pd.units.map((x) => x.unit)]) expect(u.unit, `${p.id} ${u.id}`).not.toBeNull();
    }
  });

  it('labels are unique even though official names repeat', async () => {
    const I = await api();
    const labels = I.all.map((p) => p.label);
    expect(new Set(labels).size).toBe(labels.length);
    expect(I.get(29)!.label).toBe('Militia, Archers, Hvy Inf (+ Scout)');
    expect(I.get(27)!.label).toMatch(/^Militia, Archers, Hvy Inf \(units 30\/17\/38\)$/);
    expect(I.get(25)!.label).toBe('Barbarians');
  });

  it('25 Barbarians: two Barbarians and a chief, PD with the default multiplier', async () => {
    const p = (await api()).get(25)!;
    expect(p.name).toBe('Barbarians');
    expect(ids(p.recruits)).toEqual([139, 140]);
    expect(ids(p.commanders)).toEqual([141]);
    expect(p.recruits[0].name).toBe('Barbarian');
    expect(p.pd.units.map((u) => [u.slot, u.unit.id, u.mult, u.multExplicit])).toEqual([
      ['a', 139, 10, false],
      ['b', 140, 10, false],
    ]);
    expect(p.pd.commander).toMatchObject({ source: 'defcom1', unit: { id: 141 } });
    expect(p.pdCounts(20).map((c) => c.count)).toEqual([20, 20]);
    expect(p.availability.byEra.EA).toEqual(['forest', 'mountain', 'waste', 'plains']);
    expect(p.verification.pd).toMatch(/confirmed in game/);
  });

  it('27: three PD slots with a 5/10 multiplier on the third', async () => {
    const p = (await api()).get(27)!;
    expect(ids(p.recruits)).toEqual([30, 17, 38]);
    expect(ids(p.commanders)).toEqual([34, 240]);
    expect(p.pd.units.map((u) => [u.unit.id, u.mult])).toEqual([[30, 10], [17, 10], [38, 5]]);
    expect(p.pdCounts(10).map((c) => c.count)).toEqual([10, 10, 5]);
    expect(p.isPriest).toBe(true);
    expect(p.isMage).toBe(false);
  });

  it('77 Atavi Apes: recruits, PD and chieftain', async () => {
    const p = (await api()).get(77)!;
    expect(p.name).toBe('Atavi Apes');
    expect(ids(p.recruits)).toEqual([1118, 1121, 1122]);
    expect(p.pd.units.map((u) => u.unit.id)).toEqual([1118, 1121, 1122]);
    expect(p.pd.commander!.unit.id).toBe(1127);
    expect(p.availability.terrains).toEqual(['forest']);
  });

  it('38 Hoburg: the first defunit1b (273) is used, the shadowed 271 is only listed', async () => {
    const p = (await api()).get(38)!;
    expect(p.pd.units.map((u) => [u.slot, u.unit.id, u.mult])).toEqual([
      ['a', 483, 10],
      ['b', 273, 10],
    ]);
    expect(p.pd.raw.map((x) => x[0])).toEqual(['defunit1', 'defunit1b', 'defmult1c', 'defcom1']);
    expect(p.pd.shadowed).toHaveLength(1);
    expect(p.pd.shadowed[0]).toMatchObject({ key: 'defunit1b', value: 271 });
    expect(p.pd.shadowed[0].unit!.name).toBe('Burgmeister Guard');
    expect(p.verification.shadowedPd).toMatch(/first match confirmed/);
  });

  it('88 Ko-Oni: the engine-only alternative commander (key 235) is the PD commander', async () => {
    const p = (await api()).get(88)!;
    expect(p.pd.raw).toEqual([['defunit1', 1836]]);
    expect(p.pd.commander).toMatchObject({ source: 'altPdCommander', unit: { id: 1609 }, overridesDefcom1: null, uncertain: false });
    expect(p.verification.altPdCommander).toBe('confirmed in game');
    // the Demon Priest has holy level and a random path pick
    expect(p.isPriest).toBe(true);
    expect(p.paths.random.length).toBeGreaterThan(0);
  });

  it('105 Wet Ones: key 230 is kept as unused data and does not replace the commander', async () => {
    const p = (await api()).get(105)!;
    expect(p.pd.unusedData!.id).toBe(1638);
    expect(p.pd.commander).toMatchObject({ source: 'defcom1', unit: { id: 1638 } });
    expect(p.verification.pd).toMatch(/confirmed in game \(units, multipliers, commander\)/);
  });

  it('aggregates mage paths from recruitable commanders', async () => {
    const I = await api();
    const shaman = I.get(103)!; // Cynocephalian Shaman: random S/D/N and A/E/N picks, sacred but no priest level
    expect(shaman.isMage).toBe(true);
    expect(shaman.isPriest).toBe(false);
    expect(shaman.paths.random.map((r) => [r.paths, r.chance])).toEqual([['SDN', 100], ['AEN', 50]]);
    expect(shaman.paths.letters).toEqual(['A', 'E', 'S', 'D', 'N']);
    const barb = I.get(25)!;
    expect(barb.isMage || barb.isPriest).toBe(false);
    expect(barb.paths.letters).toEqual([]);
  });

  it('terrain availability: lists per era, special-roll eras, and ids no generator gives', async () => {
    const I = await api();
    expect(I.get(88)!.availability.byEra).toEqual({ EA: ['cave', 'mountain'], MA: ['cave'], LA: ['cave'] });
    expect(I.get(65)!.availability.specialEras).toEqual(['EA', 'MA', 'LA']);
    expect(I.get(85)!.availability.specialEras).toEqual(['EA']);
    expect(I.get(106)!.availability.never).toBe(true);
    expect(I.get(25)!.availability.never).toBe(false);
  });

  it('pdTroopCount is PD * mult / 10 rounded down in one place', () => {
    expect(pdTroopCount(10, 10)).toBe(10);
    expect(pdTroopCount(10, 5)).toBe(5);
    expect(pdTroopCount(7, 15)).toBe(10);
    expect(pdTroopCount(3, 5)).toBe(1);
  });

  it('reverse index: unit -> poptypes', async () => {
    const I = await api();
    const barbarian = I.byUnit(139);
    expect(ids(barbarian.recruit)).toEqual([25]);
    expect(ids(barbarian.pdUnit)).toEqual([25]);
    expect(barbarian.commander).toEqual([]);
    // the Priest commander is in many recruit lists; the Demon Priest is Ko-Oni's PD commander through key 235
    expect(I.byUnit(240).commander.length).toBeGreaterThan(10);
    expect(ids(I.byUnit(1609).pdCommander)).toContain(88);
    expect(ids(I.byUnit(1609).commander)).toContain(88);
    expect(I.byUnit(999999)).toEqual({ recruit: [], commander: [], pdUnit: [], pdCommander: [] });
  });
});

describe('DMI.Independents with mods', () => {
  it('a mod editing poptype 25 marks it modded with the file name and updates derived data', async () => {
    const DMI = await withMods([{ name: 'edit.dm', text: '#selectpoptype 25\n#addrecunit 30\n#defmult1 20\n#defunit1c 30\n#end\n' }]);
    const I = DMI.Independents as IndependentsApi;
    expect(DMI.modMessages).toEqual([]);
    const p = I.get(25)!;
    expect(p.modded).toBe(true);
    expect(p.modfiles).toEqual(['edit.dm']);
    expect(p.vanilla).toBe(true);
    expect(p.name).toBe('Barbarians');
    expect(ids(p.recruits)).toEqual([139, 140, 30]);
    expect(p.pd.units.map((u) => [u.slot, u.unit.id, u.mult])).toEqual([
      ['a', 139, 20],
      ['b', 140, 10],
      ['c', 30, 10],
    ]);
    expect(p.pdCounts(10).map((c) => c.count)).toEqual([20, 10, 10]);
    expect(ids(I.byUnit(30).recruit)).toContain(25);
    // untouched ones stay unmodded
    expect(I.get(26)!.modded).toBe(false);
    expect(I.all.filter((x) => x.modded).map((x) => x.id)).toEqual([25]);
  });

  it('a mod adding id 150 creates "Poptype 150" with no official name or terrain', async () => {
    const DMI = await withMods([{ name: 'new.dm', text: '#selectpoptype 150\n#addrecunit 89\n#addreccom 92\n#defunit1 89\n#defcom1 92\n#end\n' }]);
    const I = DMI.Independents as IndependentsApi;
    expect(DMI.modMessages).toEqual([]);
    expect(I.all.length).toBe(83);
    const p = I.get(150)!;
    expect(p.name).toBe('Poptype 150');
    expect(p.label).toBe('Poptype 150');
    expect(p.nameSource).toBeNull();
    expect(p.vanilla).toBe(false);
    expect(p.modded).toBe(true);
    expect(p.modfiles).toEqual(['new.dm']);
    expect(p.availability.never).toBe(true);
    expect(p.pd.commander).toMatchObject({ source: 'defcom1', unit: { id: 92 } });
    expect(ids(I.get(150)!.recruits)).toEqual([89]);
  });

  it('a mod editing poptype 88 sets uncertain on the key-235 PD commander', async () => {
    const DMI = await withMods([{ name: 'e.dm', text: '#selectpoptype 88\n#defcom1 34\n#end\n' }]);
    const p = (DMI.Independents as IndependentsApi).get(88)!;
    expect(p.pd.commander).toMatchObject({ source: 'altPdCommander', unit: { id: 1609 }, uncertain: true });
    expect(p.pd.commander!.overridesDefcom1!.id).toBe(34);
  });

  it('an undefined unit in a mod keeps the id and a placeholder name', async () => {
    const DMI = await withMods([{ name: 'x.dm', text: '#selectpoptype 151\n#addrecunit 899999\n#end\n' }]);
    const u = (DMI.Independents as IndependentsApi).get(151)!.recruits[0];
    expect(u).toEqual({ id: 899999, unit: null, name: 'Unit 899999' });
  });
});
